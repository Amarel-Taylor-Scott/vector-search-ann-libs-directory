"""Generate README.md from the curated ANN-libraries registry."""

from __future__ import annotations

from collections import defaultdict

from __version__ import __version__
from data import TOOLS, Category, Tool


def _badge(label: str, message: str, color: str) -> str:
    label = label.replace(" ", "%20")
    message = str(message).replace(" ", "%20").replace("-", "--")
    return f"![{label}](https://img.shields.io/badge/{label}-{message}-{color})"


def _source(t: Tool) -> str:
    if t.open_source:
        return "🟢 OSS"
    if t.license != "Proprietary":
        return "🔃 Source-available"
    return "🔒 Proprietary"


def _row(t: Tool) -> str:
    name = f"[{t.name}]({t.url})" if t.url else t.name
    return f"| {name} | {t.org} | {_source(t)} | {t.license} | {t.note} |"


def generate() -> str:
    total = len(TOOLS)
    oss = sum(1 for t in TOOLS if t.open_source)
    categories = sorted({t.category for t in TOOLS}, key=lambda c: c.label)

    by_cat: dict[Category, list[Tool]] = defaultdict(list)
    for t in TOOLS:
        by_cat[t.category].append(t)

    out: list[str] = []
    out.append("<!-- AUTO-GENERATED by report.py — run `python main.py generate` to refresh. -->")
    out.append("# 🧮 Vector Search & ANN Libraries Directory\n")
    out.append(" ".join([
        _badge("version", __version__, "blue"),
        _badge("libraries", total, "green"),
        _badge("open%20source", oss, "brightgreen"),
        _badge("categories", len(categories), "purple"),
        "[![CI](https://github.com/Amarel-Taylor-Scott/vector-search-ann-libs-directory/actions/workflows/ci.yml/badge.svg)]"
        "(https://github.com/Amarel-Taylor-Scott/vector-search-ann-libs-directory/actions/workflows/ci.yml)",
        "[![License: MIT](https://img.shields.io/badge/License-MIT-yellow.svg)](LICENSE)",
    ]))
    out.append("")
    out.append("> A curated, machine-readable directory of **approximate-nearest-neighbor (ANN) / "
               "vector-search libraries** — the embeddable indexes and algorithms (HNSW graphs, "
               "trees, quantization) that power similarity search.\n")
    out.append("Distinct from vector *databases* (storage engines/services) and *embedding "
               "models* (which produce the vectors): these are the libraries you embed to build "
               "and query an index. Ships a small CLI to search/filter/export.\n")

    out.append("## Quick start\n")
    out.append("```bash")
    out.append("pip install -e .                # stdlib-only; no runtime deps")
    out.append("annlib-dir list                 # list all")
    out.append("annlib-dir list --category graph_hnsw")
    out.append("annlib-dir search quantization  # search name/org/note/tags")
    out.append("annlib-dir export --format csv > ann-libs.csv")
    out.append("annlib-dir generate             # regenerate this README")
    out.append("```\n")

    out.append("The [MCP Servers Directory](https://github.com/Amarel-Taylor-Scott/mcp-servers-directory#quick-start) "
               "bundles a pinned snapshot of this catalog. Install its CLI once to search the snapshot offline.\n")
    out.append("```bash")
    out.append("pipx install git+https://github.com/Amarel-Taylor-Scott/mcp-servers-directory.git")
    out.append('mcp-dir search "CAGRA GPU acceleration" --scope libraries --mode bm25 --limit 3')
    out.append("```\n")
    out.append("This query finds NVIDIA cuVS. Add `--format json` for the project URL and pinned catalog source. "
               "[More search examples](https://github.com/Amarel-Taylor-Scott/mcp-servers-directory/blob/main/resources/search-and-retrieval.md)\n")

    out.append("## At a glance\n")
    out.append(f"- **{total}** libraries across **{len(categories)}** categories")
    out.append(f"- 🟢 **{oss}** open source\n")

    out.append("## Directory\n")
    for cat in sorted(by_cat, key=lambda c: c.label):
        tools = sorted(by_cat[cat], key=lambda t: t.name.lower())
        out.append(f"### {cat.label} ({len(tools)})\n")
        out.append("| Library | Org | Source | License | Notes |")
        out.append("|---------|-----|--------|---------|-------|")
        out.extend(_row(t) for t in tools)
        out.append("")

    out.append("## Choosing one (rules of thumb)\n")
    out.append("- **Default workhorse:** FAISS (IVF/PQ/HNSW, CPU & GPU).")
    out.append("- **Lightweight HNSW:** hnswlib, usearch, Voyager.")
    out.append("- **Static, memory-mapped trees:** Annoy.")
    out.append("- **Billion-scale on disk:** DiskANN.")
    out.append("- **Pure-Python / Numba:** PyNNDescent.\n")

    out.append("## Legend\n")
    out.append("🟢 open source (license shown) · 🔃 source-available · 🔒 proprietary.\n")

    out.append("## Contributing\n")
    out.append("Add or correct an entry in [`data.py`](data.py), run `python main.py generate`, "
               "and open a PR. See [CONTRIBUTING.md](CONTRIBUTING.md) and "
               "[CODE_OF_CONDUCT.md](CODE_OF_CONDUCT.md). Keep the focus on embeddable ANN "
               "*libraries* (not vector databases or embedding models); record the EXACT license; "
               "omit anything you can't verify.\n")

    out.append("## License\n")
    out.append("[MIT](LICENSE) © Amarel Taylor Scott. Catalog metadata only; each library's own "
               "license/terms govern its use.\n")
    return "\n".join(out)


if __name__ == "__main__":
    print(generate())
